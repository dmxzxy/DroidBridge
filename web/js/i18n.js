// 界面语言：?lang= > 手动选择 > 服务端语言（桌面版通过 ?lang= 传入）> 浏览器语言
let LANG = (() => {
  const q = new URLSearchParams(location.search).get('lang');
  const v = localStorage.getItem('db_lang') || q || (navigator.language || 'en');
  return /^zh/i.test(v) ? 'zh' : 'en';
})();
document.documentElement.lang = LANG === 'zh' ? 'zh-CN' : 'en';
/** 翻译：中文原文作为键；{0}、{1} 为参数 */
function t(zh, ...args) {
  const s = LANG === 'zh' ? zh : (EN[zh] !== undefined ? EN[zh] : zh);
  return args.length ? s.replace(/\{(\d)\}/g, (_, i) => args[+i]) : s;
}
