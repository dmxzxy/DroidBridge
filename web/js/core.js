function toast(text, opt = {}) {
  const dot = h('span', { class: 'dot' + (opt.kind ? ' ' + opt.kind : '') });
  const label = h('span', {}, text);
  const el = h('div', { class: 'toast' }, opt.kind || opt.sticky ? dot : null, label);
  $('#toasts').append(el);
  let timer = null;
  const api = {
    set(msg, kind) { label.textContent = msg; dot.className = 'dot' + (kind ? ' ' + kind : ''); if (!dot.isConnected) el.prepend(dot); return api; },
    close(ms = 0) { clearTimeout(timer); timer = setTimeout(() => el.remove(), ms); },
  };
  if (!opt.sticky) api.close(opt.ms || 2600);
  return api;
}
